/**
 * Concatenate native POS SQL into one SQL Editor paste file.
 * Source of truth remains supabase/migrations/*.sql
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const files = [
  "scripts/apply-pos-integrations.sql",
  "supabase/migrations/20260828160000_native_pos_checkout.sql",
  "supabase/migrations/20260828180000_payment_intents.sql",
  "supabase/migrations/20260828190000_payment_intents_card_terminal.sql",
  "supabase/migrations/20260828200000_pos_sale_invoice.sql",
  "supabase/migrations/20260828210000_pos_registers.sql",
  "supabase/migrations/20260828220000_pos_register_sessions.sql",
  "supabase/migrations/20260828230000_pos_return_audit.sql",
  "supabase/migrations/20260828240000_pos_multibrand_catalog.sql",
  "supabase/migrations/20260828250000_pos_audit_trail.sql",
  "supabase/migrations/20260828260000_pos_rls_tenant_integrity.sql",
  "supabase/migrations/20260828270000_organizations_business_type.sql",
  "supabase/migrations/20260828280000_plans_pos_feature.sql",
  "supabase/migrations/20260828290000_pos_staff_invite.sql",
  "supabase/migrations/20260828300000_pos_registers_unique_per_brand.sql",
];

const header = `-- Native POS schema for Supabase SQL Editor. Safe to re-run.
-- Applies webhook POS tables (if missing) then every 20260828 native-POS migration in order.
-- Do not run 20260828120000_drop_affiliate_program.sql here.
-- Generated by scripts/generate-apply-native-pos.mjs — edit the migrations, then regenerate.

`;

const body = files
  .map((rel) => {
    const sql = readFileSync(join(root, rel), "utf8").trimEnd();
    return `-- ═══════════════════════════════════════════════════════════════════════════\n-- ${rel}\n-- ═══════════════════════════════════════════════════════════════════════════\n\n${sql}\n`;
  })
  .join("\n");

const out = join(root, "scripts/apply-native-pos.sql");
writeFileSync(out, header + body);
console.log(`Wrote ${out}`);
